import { Link } from "react-router-dom";
import { Card, PageHeader, Button } from "../ui";
import { openOnboarding } from "../components/Onboarding";

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <Card style={{ padding: 20, marginBottom: 16 }}>
      <h2 style={{ margin: "0 0 10px", fontSize: 18 }}>{title}</h2>
      <div style={{ color: "var(--muted,#374151)", lineHeight: 1.6, fontSize: 14.5 }}>{children}</div>
    </Card>
  );
}
function Step({ n, children }: { n: number; children: React.ReactNode }) {
  return (
    <li style={{ display: "flex", gap: 10, alignItems: "flex-start", marginBottom: 8 }}>
      <span style={{ flex: "0 0 auto", width: 22, height: 22, borderRadius: 11, background: "var(--accent,#1B7F4B)",
        color: "#fff", fontSize: 12, fontWeight: 700, display: "grid", placeItems: "center" }}>{n}</span>
      <span>{children}</span>
    </li>
  );
}

export default function GettingStartedPage() {
  return (
    <>
      <PageHeader
        title="Getting started"
        description="How to use the vGreens AI platform to train, run and manage models."
        actions={<Button variant="primary" onClick={openOnboarding}>Replay onboarding</Button>}
      />

      <Section title="Platform overview">
        The platform runs your AI jobs on the shared GPU server instead of your laptop. The flow is:
        <p style={{ margin: "10px 0 0", fontFamily: "monospace", fontSize: 13, background: "var(--code-bg,#0f3d2e0d)",
          padding: "10px 12px", borderRadius: 8, overflowX: "auto" }}>
          AI engineer → Job API → RabbitMQ queue → GPU workers → Docker + NVIDIA runtime → NAS → Monitoring → Model registry
        </p>
        Clients never touch the GPU or storage directly — everything goes through the Job API, which is what makes
        authorisation, monitoring and traceability possible.
      </Section>

      <Section title="First-time checklist">
        <ul style={{ listStyle: "none", padding: 0, margin: 0 }}>
          <Step n={1}>Sign in and confirm your role (viewer / operator / admin).</Step>
          <Step n={2}>Open <Link to="/monitoring">Monitoring</Link> and check the platform is healthy and GPUs are available.</Step>
          <Step n={3}>Make sure your model’s Docker image is built (via GitLab CI) and your dataset is frozen.</Step>
          <Step n={4}>Submit your first job from <Link to="/submit">Submit job</Link>.</Step>
          <Step n={5}>Watch it in <Link to="/jobs">Jobs</Link> and read the logs.</Step>
          <Step n={6}>Check outputs, then validate and (admin) promote the model.</Step>
        </ul>
      </Section>

      <Section title="Submit your first training job">
        <ol style={{ margin: "0 0 0 18px", padding: 0 }}>
          <li>Go to <Link to="/submit">Submit job</Link> and choose <b>Training</b>.</li>
          <li>Enter the model name and select its Docker image.</li>
          <li>Select a frozen dataset (name:version).</li>
          <li>Choose the GPU count (1 or 2 — see below).</li>
          <li>Submit. The platform stores the job, queues it, and runs it on a GPU.</li>
        </ol>
        Inference (processing) jobs work the same way but serve the <b>active</b> promoted model and produce a
        <code> report.json</code>.
      </Section>

      <Section title="Multi-GPU: how it really works">
        <p style={{ marginTop: 0 }}>
          <span style={{ display: "inline-block", background: "#B8860B", color: "#fff", fontSize: 11,
            fontWeight: 700, borderRadius: 6, padding: "2px 8px", marginRight: 6 }}>IMPORTANT</span>
          Requesting <b>2 GPUs</b> exposes both GPUs to the container, but they are only <i>used</i> if the training
          code runs a distributed strategy (PyTorch DDP / <code>torchrun</code>, TF MirroredStrategy, …).
        </p>
        <ul>
          <li>Models generated by <b>Onboard a model</b> launch multi-GPU automatically (the entrypoint relaunches
              training under <code>torchrun --nproc_per_node=$GPU_COUNT</code>).</li>
          <li>A custom, single-process image will see 2 GPUs but only use one (<code>cuda:0</code>).</li>
          <li>A 2-GPU job waits in the queue until <b>both</b> GPUs are free — it is never split onto one, and never
              failed just for waiting.</li>
          <li>Verify inside a container: <code>python -c "import torch; print(torch.cuda.device_count())"</code> → 2.</li>
        </ul>
      </Section>

      <Section title="Monitoring">
        The <Link to="/monitoring">Monitoring</Link> page updates live (no manual refresh): GPU usage, memory and
        temperature per GPU, queued and active jobs, worker status, RabbitMQ, NAS mount and Docker status, and the
        latest errors. Each job also exposes its own logs.
      </Section>

      <Section title="Outputs & model registry">
        <ul style={{ marginTop: 0 }}>
          <li>Every job writes to a unique NAS folder the platform chooses; retrieve results by job id.</li>
          <li>Training produces <code>model.pt</code>, <code>eval/metrics.json</code> and an evaluation report.</li>
          <li>A run registers a candidate version; if it clears its thresholds it becomes promotable.</li>
          <li>An admin <b>promotes</b> a version to <b>active</b>; processing serves the active model.</li>
          <li><b>Rollback</b> restores the previous active version if a regression appears.</li>
        </ul>
      </Section>

      <Section title="Troubleshooting">
        <ul style={{ marginTop: 0 }}>
          <li><b>Job stuck in “queued”:</b> no free worker, or a 2-GPU job waiting for both GPUs.</li>
          <li><b>GPU unavailable:</b> both GPUs busy — the job waits, it is not failed.</li>
          <li><b>Image pull failed:</b> check the image reference and that CI published it.</li>
          <li><b>CUDA / out-of-memory:</b> lower batch size or image size (raise gradient accumulation).</li>
          <li><b>Output missing:</b> the run didn’t reach exit 0 — read the job logs.</li>
          <li><b>2 GPUs requested but 1 used:</b> the training code is single-process; use an onboarded model or add DDP.</li>
          <li><b>Monitoring disconnected:</b> the dashboard reconnects automatically; if not, the API/stream may be down.</li>
        </ul>
      </Section>
    </>
  );
}
